public class BatasTipeData {
    public static void main(String[] args)  {
    //Byte mempunyai batas angka dari -128 sampai 127
    System.out.println("Byte minimal= " + Byte.MIN_VALUE);
    System.out.println("Byte maksimal= " + Byte.MAX_VALUE);
    //Short bisa digunakan untuk menyimpan angka lebih banyak dari byte
System.out.println("Short minimal= " + Short.MIN_VALUE);
System.out.println("Short maksimal= " + Short.MAX_VALUE);
//Int bisa digunakan untuk menyimpan angka lebih besar dari Short
System.out.println("Int minimal= " + Integer.MIN_VALUE);
System.out.println("Int maksimal= " + Integer.MAX_VALUE);
//Long bisa digunakan untuk menyimpan angka yang lebih besar lagi
System.out.println("Long minimal= " + Long.MIN_VALUE);
System.out.println("Long maksimal= " + Long.MAX_VALUE);
//Float bisa digunakan untuk angka pecahan dan juga mempunyai batas yan besar
System.out.println("Float minimal= " + - Float.MAX_VALUE);
System.out.println("Float maksimal= " + Float.MAX_VALUE);
//Double bisa digunakan untuk menyimpan angka pecahan dengan batas yang lebih besar
System.out.println("Double minimal= " + - Double.MAX_VALUE);
System.out.println("Double maksimal= " + Double.MAX_VALUE);     
    }
}
