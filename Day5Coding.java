public class App {
    public static void main(String[] args)  {
        // double dipakai untuk menyimpan sebuah angka yang bernilai pecahan
        double nilai = 86.75;
        System.out.println("double (nilai) = " + nilai);
        // float dipakai untuk menyimpan  sebuah angka pecahan,tapi ketelitiannya lebih rendah
        // huruf f dipakai untuk menandakan angka tersebut bertipe float
        float tinggi = 164.5f;
        System.out.println("float (tinggi) = " + tinggi);
    }
}
