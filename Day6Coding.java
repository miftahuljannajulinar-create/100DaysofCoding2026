public class DataKarakter {
    public static void main(String[] args) {
// char untuk menyimpan satu karakter 
char huruf = 'I';
System.out.println("huruf: " + huruf);
// boolean digunakan untuk menyimpan sebuah kondisi yang memiliki dua nilai
// true artinya kondisi benar terjadi
boolean hadir = true;
System.out.println("hadir: " + hadir);
// false artinya kondisi yang tidak benar terjadi
boolean izin = false;
System.out.println("izin: " + izin);

    }
}
