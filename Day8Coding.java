public class App {
    public static void main(String[] args)  {
        //Deklarasi variabel
        //Membuat variabel umur tanpa kita berikan sebuah nilai 
        int umur;

        //Inisialisasi variabel
        // memberikan sebuah nilai awal 17 pada variabel umur 
        umur = 17;
        //Menampilkan nilai awal variabel
        System.out.println("umur awal: " + umur);

        //Update variabel 
        // mengubah nilai umur dari 17 jadi 18
        umur = 18;
        //Menampilkan nilai setelah di update
        System.out.println("umur setelah di update: " + umur);
    }
}
