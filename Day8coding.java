public class Variabel {
    public static void main(String[] args)  {
// Deklarasi: adalah untuk membuat variabel tanpa memberi nilai
String nama;
//Insialisasi: adalah untuk memberikan nilai awal pada variabel
nama = "Miftahul";
// Menampilkan nilai awal variabel
System.out.println("Nama awal: " + nama);
// Update:mengubah nilai variabel
nama = "Janna";
// Menampilkan nilai setelah diubah 
System.out.println("Nama setelah diubah: " + nama);     
    }
}
