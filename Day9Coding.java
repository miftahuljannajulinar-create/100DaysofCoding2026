public class Finalvariabel {
    public static void main(String[] args)  {
 //Membuat variabel final sebagai konstanta
 //Nilai konstanta tidak dapat diubah setelah diberikan nilai
 final int Jumlah_Mahasiswa = 30;
 //Menampilkan nilai jumlah mahasiswa ke layar
 System.out.println("Jumlah mahasiswa: " + Jumlah_Mahasiswa);      
    }
}
